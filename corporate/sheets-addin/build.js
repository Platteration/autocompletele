#!/usr/bin/env node
// Bundles core/sheets.js and the modules it requires into one browser script
// that defines a global ActleSheets, plus the files the Apps Script sidebar
// includes. Plain Node, no dependencies, no network: the sources are read,
// each wrapped in a tiny CommonJS shim, and written out. Deterministic: the
// same sources give the same bytes, so the output can be rebuilt anywhere
// and compared.
//
//   node build.js              writes dist/ and apps-script/*.html here
//   node build.js --out DIR    writes DIR/dist/ and DIR/apps-script/
//
// Package mode writes what an organisation uploads (INSTALL.md): the folder an
// HTTPS host serves for Excel with a manifest made from manifest.template.xml
// and the organisation's configuration, the ribbon icons, and the Apps Script
// files. Nothing is written when the configuration is refused.
//
//   node build.js --package extle.config.json [--out DIR] [--dev]
//                              writes DIR/excel/ and DIR/apps-script/ (DIR: ./package)
"use strict";

const fs = require("node:fs");
const path = require("node:path");
const zlib = require("node:zlib");

const ROOT = path.resolve(__dirname, "..", "..");
const ENTRY = path.join(ROOT, "corporate", "core", "sheets.js");
const PANE_JS = path.join(__dirname, "pane.js");
const PANE_CSS = path.join(__dirname, "pane.css");
const TEMPLATE = path.join(__dirname, "manifest.template.xml");
const REQUIRE = /\brequire\(\s*(["'])([^"'\n]+)\1\s*\)/g;

function moduleId(file) {
  return path.relative(ROOT, file).split(path.sep).join("/");
}

/** The entry and everything it requires, depth first, each module once, in a fixed order. */
function collect(entry) {
  const modules = new Map();
  const visit = (file, from) => {
    const id = moduleId(file);
    if (modules.has(id)) return;
    if (!id || id.startsWith("..")) throw new Error("module outside the repository: " + file + (from ? " (required by " + from + ")" : ""));
    let source;
    try {
      source = fs.readFileSync(file, "utf8");
    } catch (error) {
      throw new Error("cannot read " + id + (from ? " (required by " + from + ")" : "") + ": " + error.message);
    }
    modules.set(id, source.replace(/\r\n/g, "\n"));
    for (const match of source.matchAll(REQUIRE)) {
      // Only relative requires can be bundled; a Node builtin would not run in a browser.
      if (!match[2].startsWith(".")) throw new Error(id + " requires " + match[2] + ", which a browser cannot load");
      visit(path.resolve(path.dirname(file), match[2]), id);
    }
  };
  visit(entry, null);
  return modules;
}

/** One script: a polyfill, every module as a function, a resolver for relative requires, and the entry's exports on the global. */
function bundle(modules, entryId) {
  const out = ["// extle core bundle, generated by corporate/sheets-addin/build.js from " + [...modules.keys()].join(", ") + ". Do not edit; rebuild."];
  out.push(
    "(function (root) {",
    '  "use strict";',
    "  // Object.hasOwn is ES2022; an older Office webview (WebKit before Safari 15.4) lacks it.",
    '  if (typeof Object.hasOwn !== "function") Object.hasOwn = function (object, key) { return Object.prototype.hasOwnProperty.call(Object(object), key); };',
    "  var definitions = {};",
  );
  for (const [id, source] of modules) {
    out.push("  definitions[" + JSON.stringify(id) + "] = function (module, exports, require) {", source.replace(/\n+$/, ""), "  };");
  }
  out.push(
    "  var cache = {};",
    "  function resolve(from, spec) {",
    '    var parts = from.split("/").slice(0, -1);',
    '    spec.split("/").forEach(function (part) {',
    '      if (part === "..") parts.pop();',
    '      else if (part !== ".") parts.push(part);',
    "    });",
    '    return parts.join("/");',
    "  }",
    "  function load(id) {",
    "    if (!cache[id]) {",
    "      var definition = definitions[id];",
    '      if (!definition) throw new Error("bundle has no module " + id);',
    "      var module = { exports: {} };",
    "      cache[id] = module;",
    "      definition(module, module.exports, function (spec) { return load(resolve(id, spec)); });",
    "    }",
    "    return cache[id].exports;",
    "  }",
    "  root.ActleSheets = load(" + JSON.stringify(entryId) + ");",
    '})(typeof self !== "undefined" ? self : typeof window !== "undefined" ? window : this);',
    "",
  );
  return out.join("\n");
}

/** Apps Script includes are HTML files; the tag that closes them must not appear inside. */
function inline(tag, content) {
  if (new RegExp("</" + tag, "i").test(content)) throw new Error("the " + tag + " content contains </" + tag + ">, which would end the Apps Script include early");
  return "<" + tag + ">\n" + content.replace(/\n+$/, "") + "\n</" + tag + ">\n";
}

/**
 * Build into `options.out` (default: this folder). Returns what was written.
 * @returns {{out:string, files:string[], modules:string[], bytes:number}}
 */
function build(options) {
  const out = path.resolve(options && options.out ? String(options.out) : __dirname);
  const modules = collect(ENTRY);
  const script = bundle(modules, moduleId(ENTRY));
  const includes = appsScriptIncludes(script);
  const files = {
    "dist/sheets-core.js": script,
    "apps-script/sheets-core.html": includes["sheets-core.html"],
    "apps-script/pane.html": includes["pane.html"],
  };
  for (const [name, content] of Object.entries(files)) {
    const target = path.join(out, name);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content, "utf8");
  }
  return { out, files: Object.keys(files), modules: [...modules.keys()], bytes: Buffer.byteLength(script, "utf8") };
}

/** The two files Sidebar.html includes: the bundle, and the pane with its styles. */
function appsScriptIncludes(script) {
  return {
    "sheets-core.html": inline("script", script),
    "pane.html": inline("style", fs.readFileSync(PANE_CSS, "utf8")) + inline("script", fs.readFileSync(PANE_JS, "utf8")),
  };
}

