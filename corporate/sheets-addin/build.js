// Package mode

// The name people see: NAMES.sheets.name in desktop/apps/index.js, repeated here as in the rest of
// the add-in (sheets-addin/test/hosts.test.js holds the generated manifest to that table).
const NAME = "extle";
const DEFAULT_DESCRIPTION = NAME + ": column-aware completion in Excel from your organisation's vocabularies, and blocks and formulas by trigger.";
// The example configuration's id, and the all-zero GUID: neither was generated for an organisation.
const PLACEHOLDER_IDS = ["7b1f6c9a-0000-4000-8000-000000000001", "00000000-0000-0000-0000-000000000000"];
const KEYS = ["id", "baseUrl", "providerName", "version", "supportUrl", "displayName", "description"];
const REQUIRED = ["id", "baseUrl", "providerName", "version", "supportUrl"];
const GUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
// Microsoft's Version element: 1 to 4 parts (n, n.n, n.n.n or n.n.n.n), each at most 5 digits.
const VERSION = /^\d{1,5}(\.\d{1,5}){0,3}$/;
// Lengths from Microsoft's manifest reference. DisplayName and a ShortStrings entry hold 125
// characters; the button label is "Open " and the name, so the name gets 120. ProviderName 125,
// Description 250. SourceLocation is a URL of 1 to 2018 characters.
const LIMITS = { displayName: 120, providerName: 125, description: 250, sourceLocation: 2018 };
const SOURCE_PAGE = "taskpane.html";
const ICON_SIZES = [16, 32, 64, 80]; // IconUrl 32, HighResolutionIconUrl 64, ribbon 16, 32 and 80
const ICON_COLOUR = [0x24, 0x57, 0xc5]; // pane.css --accent in the light theme; white on it is 6.5:1
// A bold lowercase e, eight by seven, drawn white on the colour.
const GLYPH = [
  "..####..",
  ".##..##.",
  "##....##",
  "########",
  "##......",
  ".##...##",
  "..#####.",
];

function isLoopback(hostname) {
  return hostname === "localhost" || hostname.endsWith(".localhost") || /^127\.\d+\.\d+\.\d+$/.test(hostname) || hostname === "[::1]";
}

/** What is wrong with one text the manifest shows; an empty list when nothing is. */
function textProblems(key, value, max, why) {
  if (typeof value !== "string") return [key + " must be a text"];
  if (!/\S/.test(value)) return [key + " is empty"];
  // XML 1.0 has no way to write most control characters, escaped or not; none belongs in a name.
  if (/[\u0000-\u001f\u007f-\u009f￾￿]/.test(value)) return [key + " holds a control character (a tab, a line break or similar)"];
  if (/[\ud800-\udbff](?![\udc00-\udfff])|(?<![\ud800-\udbff])[\udc00-\udfff]/.test(value)) return [key + " holds a broken character (half of a surrogate pair)"];
  if (value.length > max) return [key + " is " + value.length + " characters long; " + why];
  return [];
}

/** A URL the manifest holds: https, or http://localhost with --dev; localhost only with --dev. */
function urlProblems(key, value, dev, folder) {
  if (typeof value !== "string" || !value) return { problems: [key + " must be a URL"] };
  let url;
  try {
    url = new URL(value);
  } catch {
    return { problems: [key + " is not a URL: " + value] };
  }
  const problems = [];
  const local = isLoopback(url.hostname);
  if (url.protocol === "http:") {
    if (!dev || !local) problems.push(key + " must start with https:// (http:// is accepted only for localhost, with --dev)");
  } else if (url.protocol !== "https:") problems.push(key + " must start with https://");
  if (local && !dev) problems.push(key + " points at " + url.hostname + ", which Excel on other computers cannot reach; build with --dev to test on this computer");
  if (url.username || url.password) problems.push(key + " must not hold a user name or password");
  if (folder && (url.search || url.hash)) problems.push(key + " must be a folder, without ? or #");
  return { problems, url };
}

/**
 * Check a configuration and fill in its defaults. Every problem is listed in one error
 * (error.problems), so a person fixes the file once.
 * @returns {{id:string, baseUrl:string, providerName:string, version:string, supportUrl:string, displayName:string, description:string, dev:boolean}}
 */
function validateConfig(raw, options) {
  const dev = Boolean(options && options.dev);
  const problems = [];
  const isObject = Boolean(raw) && typeof raw === "object" && !Array.isArray(raw);
  const config = isObject ? raw : {};
  if (!isObject) problems.push("the configuration must be a JSON object");
  else {
    for (const key of Object.keys(config)) if (!KEYS.includes(key)) problems.push("unknown key " + JSON.stringify(key) + " (the keys are " + KEYS.join(", ") + ")");
    for (const key of REQUIRED) if (!Object.hasOwn(config, key)) problems.push(key + " is missing");
  }
  const has = (key) => Object.hasOwn(config, key);

  if (has("id")) {
    if (typeof config.id !== "string" || !GUID.test(config.id)) problems.push("id must be a GUID such as 3f2b8c1e-5d4a-4e7b-9c60-1a2b3c4d5e6f (hyphenated, no braces); generate one with: node -e \"console.log(crypto.randomUUID())\"");
    else if (PLACEHOLDER_IDS.includes(config.id.toLowerCase()) && !dev) problems.push("id " + config.id + " is a placeholder, not a GUID made for your organisation; generate one with: node -e \"console.log(crypto.randomUUID())\" (or build with --dev to test on this computer)");
  }
  if (has("version") && (typeof config.version !== "string" || !VERSION.test(config.version))) {
    problems.push("version must be 1 to 4 numbers of at most 5 digits, separated by dots, such as 1.0.0.0 (got " + JSON.stringify(config.version) + ")");
  }
  if (has("providerName")) problems.push(...textProblems("providerName", config.providerName, LIMITS.providerName, "the manifest allows " + LIMITS.providerName));
  if (has("displayName")) problems.push(...textProblems("displayName", config.displayName, LIMITS.displayName, "the manifest allows " + LIMITS.displayName + " here, since the ribbon button's label, \"Open \" and the name, may hold 125"));
  if (has("description")) problems.push(...textProblems("description", config.description, LIMITS.description, "the manifest allows " + LIMITS.description));

  let baseUrl = "";
  if (has("baseUrl")) {
    const checked = urlProblems("baseUrl", config.baseUrl, dev, true);
    problems.push(...checked.problems);
    if (checked.url && !checked.problems.length) {
      baseUrl = checked.url.href.endsWith("/") ? checked.url.href : checked.url.href + "/";
      const source = baseUrl + SOURCE_PAGE;
      if (source.length > LIMITS.sourceLocation) problems.push("baseUrl is too long: " + source + " is " + source.length + " characters, and the manifest's SourceLocation allows " + LIMITS.sourceLocation);
    }
  }
  let supportUrl = "";
  if (has("supportUrl")) {
    const checked = urlProblems("supportUrl", config.supportUrl, dev, false);
    problems.push(...checked.problems);
    if (checked.url && !checked.problems.length) supportUrl = checked.url.href;
  }

  if (problems.length) {
    const error = new Error("the configuration cannot be packaged:\n  - " + problems.join("\n  - "));
    error.problems = problems;
    throw error;
  }
  return {
    id: config.id,
    baseUrl,
    providerName: config.providerName,
    version: config.version,
    supportUrl,
    displayName: has("displayName") ? config.displayName : NAME,
    description: has("description") ? config.description : DEFAULT_DESCRIPTION,
    dev,
  };
}

/** Read and parse a configuration file; validateConfig checks it. */
function readConfig(file) {
  let text;
  try {
    text = fs.readFileSync(file, "utf8");
  } catch (error) {
    throw new Error("cannot read the configuration " + file + ": " + error.message);
  }
  try {
    return JSON.parse(text.replace(/^﻿/, ""));
  } catch (error) {
    throw new Error(file + " is not JSON: " + error.message);
  }
}

/** Text for an XML attribute value or element: the five characters XML gives a meaning, escaped. */
function escapeXml(text) {
  return String(text).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" })[c]);
}

/** Put each value, escaped, in place of its {{KEY}}; a placeholder with no value, or a stray brace pair, stops the build. */
function fillTemplate(template, values) {
  const stray = template.replace(/\{\{[A-Z_]+\}\}/g, "").match(/\{\{|\}\}/);
  if (stray) throw new Error("manifest.template.xml has a placeholder that is not {{NAME}} in capitals, near " + JSON.stringify(template.slice(Math.max(0, stray.index - 20), stray.index + 20)));
  return template.replace(/\{\{([A-Z_]+)\}\}/g, (whole, key) => {
    if (!Object.hasOwn(values, key)) throw new Error("manifest.template.xml has a placeholder build.js does not fill: " + whole);
    return escapeXml(values[key]);
  });
}

/** The manifest for a checked configuration (validateConfig). */
function manifestFor(config, template) {
  const source = template === undefined ? fs.readFileSync(TEMPLATE, "utf8") : template;
  // "--" may not appear inside an XML comment, so the note does not spell the command line.
  const note = "<!-- " + NAME + " for Excel, generated by corporate/sheets-addin/build.js in package mode from manifest.template.xml and the organisation's configuration. Change the configuration and build again rather than editing this file." + (config.dev ? " A development package, for testing on this computer only." : "") + " -->";
  return fillTemplate(source.replace(/<!-- template\b[\s\S]*?-->/, () => note), {
    ID: config.id,
    VERSION: config.version,
    PROVIDER_NAME: config.providerName,
    DISPLAY_NAME: config.displayName,
    DESCRIPTION: config.description,
    BASE_URL: config.baseUrl,
    SUPPORT_URL: config.supportUrl,
  });
}

/**
 * The icon's pixels, size by size, as RGBA rows: a rounded square in the pane's accent colour with
 * a white e. The corners are smoothed by counting which of 4 by 4 points in a pixel fall inside.
 */
function iconPixels(size) {
  const radius = Math.round((size * 3) / 16);
  const scale = Math.max(1, Math.floor((size * 0.6) / GLYPH[0].length));
  const left = Math.floor((size - GLYPH[0].length * scale) / 2);
  const top = Math.floor((size - GLYPH.length * scale) / 2);
  const pixels = Buffer.alloc(size * size * 4);
  const inside = (x, y) => {
    const dx = Math.max(radius - x, 0, x - (size - radius));
    const dy = Math.max(radius - y, 0, y - (size - radius));
    return dx * dx + dy * dy <= radius * radius;
  };
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      let covered = 0;
      for (let j = 0; j < 4; j++) for (let i = 0; i < 4; i++) if (inside(x + (i + 0.5) / 4, y + (j + 0.5) / 4)) covered++;
      const gx = Math.floor((x - left) / scale);
      const gy = Math.floor((y - top) / scale);
      const glyph = x >= left && y >= top && gy < GLYPH.length && gx < GLYPH[0].length && GLYPH[gy][gx] === "#";
      const at = (y * size + x) * 4;
      const [r, g, b] = glyph ? [255, 255, 255] : ICON_COLOUR;
      pixels[at] = r;
      pixels[at + 1] = g;
      pixels[at + 2] = b;
      pixels[at + 3] = Math.round((covered * 255) / 16);
    }
  }
  return pixels;
}

function pngChunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, "latin1");
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(zlib.crc32(Buffer.concat([head.subarray(4), data])) >>> 0, 0);
  return Buffer.concat([head, data, crc]);
}

/** An 8-bit RGBA PNG: signature, IHDR, one IDAT (rows with filter 0, deflated), IEND. */
function encodePng(size, pixels) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header[8] = 8; // bits per channel
  header[9] = 6; // RGBA
  header[10] = 0; // deflate
  header[11] = 0; // adaptive filtering, here filter 0 on every row
  header[12] = 0; // not interlaced
  const rows = Buffer.alloc(size * (1 + size * 4));
  for (let y = 0; y < size; y++) pixels.copy(rows, y * (1 + size * 4) + 1, y * size * 4, (y + 1) * size * 4);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk("IHDR", header),
    pngChunk("IDAT", zlib.deflateSync(rows, { level: 9 })),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
}

function iconPng(size) {
  return encodePng(size, iconPixels(size));
}

/** Every file under a folder, relative, with / separators. */
function filesUnder(folder) {
  if (!fs.existsSync(folder)) return [];
  const found = [];
  const walk = (dir, prefix) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
      if (entry.isDirectory()) walk(path.join(dir, entry.name), prefix + entry.name + "/");
      else found.push(prefix + entry.name);
    }
  };
  walk(folder, "");
  return found;
}

/**
 * Write the package into `options.out` (default: ./package next to this file). The configuration is
 * checked first (validateConfig), and nothing is written when it is refused. Files of an earlier
 * build are replaced; files this build does not write are left in place and listed in `extra`
 * (in apps-script/, names starting with a dot, such as clasp's .clasp.json, are not listed).
 * @returns {{out:string, dev:boolean, config:object, excel:string[], appsScript:string[], extra:string[], modules:string[]}}
 */
function buildPackage(options) {
  const config = validateConfig(options && options.config, { dev: options && options.dev });
  const out = path.resolve(options && options.out ? String(options.out) : path.join(__dirname, "package"));
  const modules = collect(ENTRY);
  const script = bundle(modules, moduleId(ENTRY));
  const includes = appsScriptIncludes(script);
  const copy = (name) => fs.readFileSync(path.join(__dirname, name));
  const excel = new Map([
    ["manifest.xml", manifestFor(config)],
    ["taskpane.html", copy("taskpane.html")],
    ["taskpane.js", copy("taskpane.js")],
    ["pane.js", copy("pane.js")],
    ["pane.css", copy("pane.css")],
    ["dist/sheets-core.js", script],
    ...ICON_SIZES.map((size) => ["assets/icon-" + size + ".png", iconPng(size)]),
  ]);
  const appsScript = new Map([
    ["Code.gs", copy("apps-script/Code.gs")],
    ["Sidebar.html", copy("apps-script/Sidebar.html")],
    ["sheets-core.html", includes["sheets-core.html"]],
    ["pane.html", includes["pane.html"]],
    ["appsscript.json", copy("apps-script/appsscript.json")],
  ]);
  const extra = [];
  for (const [folder, files] of [["excel", excel], ["apps-script", appsScript]]) {
    for (const [name, content] of files) {
      const target = path.join(out, folder, name);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
    }
    for (const name of filesUnder(path.join(out, folder))) {
      if (files.has(name) || (folder === "apps-script" && name.split("/").some((part) => part.startsWith(".")))) continue;
      extra.push(folder + "/" + name);
    }
  }
  return { out, dev: config.dev, config, excel: [...excel.keys()], appsScript: [...appsScript.keys()], extra, modules: [...modules.keys()] };
}

/** The package mode's command line: --package FILE, --out DIR, --dev; anything else is refused. */
function packageArguments(args) {
  const options = { configFile: null, out: undefined, dev: false };
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    const value = () => {
      const next = args[++i];
      if (next === undefined || next.startsWith("--")) throw new Error(arg + " needs a value");
      return next;
    };
    if (arg === "--package") options.configFile = value();
    else if (arg === "--out") options.out = value();
    else if (arg === "--dev") options.dev = true;
    else throw new Error("unknown argument " + JSON.stringify(arg) + "; package mode takes --package FILE, --out DIR and --dev");
  }
  if (!options.configFile) throw new Error("--dev needs --package FILE");
  return options;
}

function packageMain(args) {
  try {
    const options = packageArguments(args);
    const result = buildPackage({ config: readConfig(options.configFile), out: options.out, dev: options.dev });
    const lines = [
      "packaged " + result.config.displayName + " " + result.config.version + (result.dev ? " (development package, for this computer only)" : "") + " in " + result.out,
      "  excel/        serve this folder at " + result.config.baseUrl + " and upload excel/manifest.xml: " + result.excel.join(", "),
      "  apps-script/  clasp push from this folder, or paste the files into the Apps Script editor: " + result.appsScript.join(", "),
    ];
    if (result.extra.length) lines.push("  left in place, not written by this build (remove them if they are not yours): " + result.extra.join(", "));
    lines.push("  next steps: INSTALL.md");
    console.log(lines.join("\n"));
  } catch (error) {
    console.error("build.js: " + error.message);
    process.exitCode = 1;
  }
}

if (require.main === module) {
  const args = process.argv.slice(2);
  if (args.includes("--package") || args.includes("--dev")) packageMain(args);
  else {
    const at = args.indexOf("--out");
    const result = build({ out: at >= 0 ? args[at + 1] : undefined });
    console.log("built " + result.files.join(", ") + " in " + result.out + " (" + result.bytes + " bytes from " + result.modules.length + " modules)");
  }
}

module.exports = {
  build, collect, bundle, inline, ROOT, ENTRY,
  buildPackage, validateConfig, readConfig, packageArguments, manifestFor, fillTemplate, escapeXml, iconPixels, iconPng, encodePng,
  NAME, DEFAULT_DESCRIPTION, PLACEHOLDER_IDS, LIMITS, ICON_SIZES, ICON_COLOUR, TEMPLATE,
};
